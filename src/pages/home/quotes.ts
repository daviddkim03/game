const DECK_KEY = "home:quote-deck"

/** Quotes still to show this round (as indexes), and the one shown last. */
type Deck = { size: number; order: number[]; last: number }

function shuffled(count: number, random: () => number) {
  const order = Array.from({ length: count }, (_, i) => i)
  for (let i = count - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1))
    ;[order[i], order[j]] = [order[j], order[i]]
  }
  return order
}

function readDeck(): Deck | null {
  try {
    const deck = JSON.parse(
      localStorage.getItem(DECK_KEY) ?? "null"
    ) as Deck | null
    // A changed quote list makes saved indexes meaningless; start over.
    return deck?.size === QUOTES.length && Array.isArray(deck.order)
      ? deck
      : null
  } catch {
    return null
  }
}

/**
 * The quote for this page load. Quotes are dealt from a shuffled deck, so
 * every one is shown once before any repeats, and a new round never starts
 * with the quote that ended the last one.
 */
export function pickQuote(random: () => number = Math.random): Quote {
  const deck = readDeck()
  let order = deck?.order.filter((i) => i >= 0 && i < QUOTES.length) ?? []
  if (order.length === 0) {
    order = shuffled(QUOTES.length, random)
    if (order[0] === deck?.last && order.length > 1) {
      ;[order[0], order[1]] = [order[1], order[0]]
    }
  }
  const index = order.shift()!
  try {
    const next: Deck = { size: QUOTES.length, order, last: index }
    localStorage.setItem(DECK_KEY, JSON.stringify(next))
  } catch {
    // Storage can be blocked; quotes are then simply random.
  }
  return QUOTES[index]
}
